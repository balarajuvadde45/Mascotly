#!/usr/bin/env node
// Real-world integration seed: runs Mascotly against the actual Docsify project
// (github.com/docsifyjs/docsify — MIT), ingests its real repository docs via
// Mascotly's GitHub ingestor, runs the analyzer, and writes the credentials file
// that the docs site's mascot embed loads.
//
//   1. start the Mascotly server:  npm start          (repo root)
//   2. run:                      node integrations/docsify/seed.mjs
//   3. serve the docs site:      node integrations/docsify/serve.mjs
//   4. open:                     http://localhost:4321
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..', '..');
const SERVER = process.env.MASCOT_URL || 'http://localhost:4242';

function adminKey() {
  if (process.env.MASCOT_ADMIN_KEY) return process.env.MASCOT_ADMIN_KEY;
  try {
    const dataDir = path.resolve(ROOT, process.env.MASCOT_DATA_DIR || 'data');
    return JSON.parse(fs.readFileSync(path.join(dataDir, 'admin.json'), 'utf8')).key;
  } catch {
    throw new Error('Could not read the admin key. Start the server first (npm start) or set MASCOT_ADMIN_KEY.');
  }
}

async function api(method, p, body) {
  const res = await fetch(`${SERVER}/api${p}`, {
    method,
    headers: { 'x-mascot-key': adminKey(), 'content-type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const data = await res.json().catch(() => ({}));
  if (!res.ok) throw new Error(`${method} ${p} → ${res.status}: ${data.message || ''}`);
  return data;
}

async function pollJob(appId, jobId, { timeoutMs = 180000 } = {}) {
  const started = Date.now();
  for (;;) {
    const { job } = await api('GET', `/apps/${appId}/jobs/${jobId}`);
    if (job.status === 'done') return job;
    if (job.status === 'failed') throw new Error(`job failed: ${job.error}`);
    if (Date.now() - started > timeoutMs) throw new Error('job timed out');
    await new Promise((r) => setTimeout(r, 1000));
  }
}

async function main() {
  console.log(`Seeding the Docsify integration into ${SERVER} …`);

  // Reuse an existing Docsify app when present; otherwise create one.
  const { apps } = await api('GET', '/apps');
  let app = apps.find((a) => a.slug === 'docsify');
  if (app) {
    console.log(`✓ reusing existing app: ${app.id}`);
    app = (await api('GET', `/apps/${app.id}`)).app;
  } else {
    const created = await api('POST', '/apps', {
      name: 'Docsify',
      description: 'Docsify (docsifyjs/docsify) — a magical documentation site generator. Sites are created from markdown files, rendered client-side, with plugins, themes and full-text search. No static HTML build step required.',
      mascot: {
        name: 'Docsy',
        emoji: '📚',
        color: '#2ecc8f',
        greeting: "Hi! I'm Docsy 📚 — ask me anything about Docsify: setup, configuration, plugins, theming, deployment…",
        tagline: 'Docsify docs assistant',
        personality: 'helpful and concrete. You answer with short markdown answers, exact configuration snippets and links to the docs.',
        suggestions: ['How do I create a new docs site?', 'How does the search plugin work?', 'How do I deploy docs to GitHub Pages?'],
      },
    });
    app = created.app;
    console.log(`✓ app created: ${app.id}`);
  }

  // Ingest the REAL docsify repository (README + docs tree) via GitHub ingest —
  // but only when it isn't already indexed (re-runs stay idempotent).
  const { sources } = await api('GET', `/apps/${app.id}/sources`);
  const existingRepoSource = sources.find((s) => s.type === 'github' && s.detail?.repo === 'docsifyjs/docsify' && s.status === 'ready');
  if (existingRepoSource) {
    console.log(`✓ docsifyjs/docsify already indexed (${existingRepoSource.chunkCount} chunks) — skipping ingest`);
  } else {
    const src = await api('POST', `/apps/${app.id}/sources`, { type: 'github', repo: 'docsifyjs/docsify' });
    if (src.jobId) {
      console.log(`… ingesting docsifyjs/docsify (job ${src.jobId})`);
      const job = await pollJob(app.id, src.jobId);
      console.log(`✓ ingested ${job.result.docCount || ''} docs → ${job.result.chunkCount || src.chunkCount || ''} chunks`.trim());
    } else {
      console.log(`✓ ingested repo docs (${src.chunkCount} chunks)`);
    }
  }

  // Analyze so the mascot has a real profile.
  const { jobId } = await api('POST', `/apps/${app.id}/analyze`);
  const job = await pollJob(app.id, jobId);
  console.log(`✓ analyzer finished (engine: ${job.result.engine}, ${job.result.features} features, ${job.result.faqs} FAQs)`);

  // Write credentials for the docs site's mascot embed.
  const out = path.join(__dirname, 'docs', 'mascot-credentials.js');
  fs.writeFileSync(out,
    `// Auto-generated by integrations/docsify/seed.mjs — safe to regenerate.\nwindow.MASCOT_APP_ID = ${JSON.stringify(app.id)};\nwindow.MASCOT_PUBLIC_KEY = ${JSON.stringify(app.publicKey)};\nwindow.MASCOT_SERVER = ${JSON.stringify(SERVER)};\n`);
  console.log(`✓ wrote ${path.relative(ROOT, out)}`);

  console.log('\n──────────────────────────────────────────────────────');
  console.log('Docsify (the real OSS project) now has a Mascotly.');
  console.log('Serve the docs site and open it:');
  console.log(`  node integrations/docsify/serve.mjs`);
  console.log(`  → http://localhost:4321`);
  console.log('Ask Docsy things like "what is docsify?" or "how does SSR work?"');
  console.log('──────────────────────────────────────────────────────');
}

main().catch((err) => {
  console.error('Seed failed:', err.message);
  process.exit(1);
});
